'use strict';

/**
 * Minimal, dependency-free demo dashboard.
 *
 * Served only when enabled (defaults to on outside production). The page
 * asks the operator for an API key, stores it in localStorage, and calls
 * the authenticated /v1 API directly from the browser. No secrets are
 * embedded in the HTML.
 */
function renderDashboard() {
  const html = [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<title>SignalMesh Demo Dashboard</title>',
    '<style>',
    ':root{color-scheme:light dark;--bg:#0e1116;--panel:#161b22;--line:#2b333d;--text:#e6edf3;--muted:#8b949e;--ok:#3fb950;--warn:#d29922;--err:#f85149;--accent:#58a6ff}',
    '*{box-sizing:border-box}body{margin:0;font:14px/1.5 ui-sans-serif,system-ui,Segoe UI,Roboto,sans-serif;background:var(--bg);color:var(--text)}',
    'header{padding:18px 24px;border-bottom:1px solid var(--line);display:flex;align-items:center;gap:14px;flex-wrap:wrap}',
    'h1{font-size:18px;margin:0;font-weight:700;letter-spacing:.2px}h2{font-size:14px;margin:0 0 10px;color:var(--muted);text-transform:uppercase;letter-spacing:.08em}',
    'main{padding:20px 24px;display:grid;gap:20px}',
    '.bar{display:flex;gap:8px;align-items:center;flex-wrap:wrap}',
    'input{background:var(--panel);border:1px solid var(--line);color:var(--text);padding:8px 10px;border-radius:8px;min-width:280px}',
    'button{background:var(--accent);color:#04121f;border:0;padding:8px 12px;border-radius:8px;font-weight:600;cursor:pointer}',
    'button.ghost{background:transparent;color:var(--text);border:1px solid var(--line)}',
    'button:active{transform:translateY(1px)}',
    '.panel{background:var(--panel);border:1px solid var(--line);border-radius:12px;padding:16px;overflow:auto}',
    'table{width:100%;border-collapse:collapse;font-size:13px}th,td{text-align:left;padding:7px 10px;border-bottom:1px solid var(--line);white-space:nowrap}',
    'th{color:var(--muted);font-weight:600}tr:last-child td{border-bottom:0}',
    '.pill{display:inline-block;padding:2px 8px;border-radius:999px;font-size:12px;font-weight:600}',
    '.s-succeeded{background:rgba(63,185,80,.15);color:var(--ok)}',
    '.s-dead_lettered{background:rgba(248,81,73,.15);color:var(--err)}',
    '.s-retry_scheduled,.s-processing{background:rgba(210,153,34,.15);color:var(--warn)}',
    '.s-pending,.s-cancelled{background:rgba(139,148,158,.15);color:var(--muted)}',
    '.muted{color:var(--muted)}.status{color:var(--muted);font-size:12px}',
    'code{font-family:ui-monospace,SFMono-Regular,Consolas,monospace;font-size:12px}',
    '</style>',
    '</head>',
    '<body>',
    '<header><h1>SignalMesh</h1><span class="muted">delivery dashboard</span><span class="status" id="status"></span></header>',
    '<main>',
    '  <section class="panel">',
    '    <div class="bar">',
    '      <input id="key" placeholder="Paste API key (rel_...)" autocomplete="off" />',
    '      <button id="save">Connect</button>',
    '      <button class="ghost" id="refresh">Refresh</button>',
    '      <span class="muted">Auto-refreshes every 3s</span>',
    '    </div>',
    '  </section>',
    '  <section class="panel"><h2>Recent events</h2><table><thead><tr><th>Event</th><th>Type</th><th>Created</th><th>Deliveries</th></tr></thead><tbody id="events"><tr><td colspan="4" class="muted">Connect with an API key.</td></tr></tbody></table></section>',
    '  <section class="panel"><h2>Deliveries</h2><table><thead><tr><th>Delivery</th><th>Event</th><th>Type</th><th>Status</th><th>Attempts</th><th>Last status</th><th>Last error</th><th></th></tr></thead><tbody id="deliveries"><tr><td colspan="8" class="muted">No deliveries yet.</td></tr></tbody></table></section>',
    '</main>',
    '<script>',
    '(function () {',
    '  var keyInput = document.getElementById("key");',
    '  var statusEl = document.getElementById("status");',
    '  keyInput.value = localStorage.getItem("signalmesh_key") || "";',
    '  function getKey() { return keyInput.value.trim(); }',
    '  function esc(v) { return String(v == null ? "" : v).replace(/[&<>"]/g, function (c) { return {"&":"&amp;","<":"&lt;",">":"&gt;","\\"":"&quot;"}[c]; }); }',
    '  function api(path, opts) {',
    '    var k = getKey();',
    '    if (!k) return Promise.reject(new Error("no key"));',
    '    return fetch(path, Object.assign({ headers: { authorization: "Bearer " + k } }, opts || {})).then(function (r) {',
    '      return r.json().then(function (body) { return { status: r.status, body: body }; });',
    '    });',
    '  }',
    '  function pill(status) { return "<span class=\\"pill s-" + esc(status) + "\\">" + esc(status) + "</span>"; }',
    '  function renderEvents(rows) {',
    '    var tbody = document.getElementById("events");',
    '    if (!rows.length) { tbody.innerHTML = "<tr><td colspan=\\"4\\" class=\\"muted\\">No events yet.</td></tr>"; return; }',
    '    tbody.innerHTML = rows.map(function (e) {',
    '      return "<tr><td><code>" + esc(e.event_id) + "</code></td><td>" + esc(e.event_type) + "</td><td>" + esc(e.created_at) + "</td><td>" + esc((e.deliveries || []).length) + "</td></tr>";',
    '    }).join("");',
    '  }',
    '  function renderDeliveries(rows) {',
    '    var tbody = document.getElementById("deliveries");',
    '    if (!rows.length) { tbody.innerHTML = "<tr><td colspan=\\"8\\" class=\\"muted\\">No deliveries yet.</td></tr>"; return; }',
    '    tbody.innerHTML = rows.map(function (d) {',
    '      var canReplay = d.status === "dead_lettered" || d.status === "succeeded" || d.status === "cancelled";',
    '      var action = canReplay ? "<button class=\\"ghost\\" data-replay=\\"" + esc(d.id) + "\\">Replay</button>" : "";',
    '      return "<tr><td><code>" + esc(d.id) + "</code></td><td><code>" + esc(d.event_id) + "</code></td><td>" + esc(d.event_type) + "</td><td>" + pill(d.status) + "</td><td>" + esc(d.attempt_count) + "</td><td>" + esc(d.last_status_code == null ? "-" : d.last_status_code) + "</td><td>" + esc(d.last_error == null ? "-" : d.last_error) + "</td><td>" + action + "</td></tr>";',
    '    }).join("");',
    '  }',
    '  function refresh() {',
    '    if (!getKey()) { statusEl.textContent = "add an API key to load data"; return; }',
    '    statusEl.textContent = "loading...";',
    '    Promise.all([api("/v1/events?limit=15"), api("/v1/deliveries?limit=40")]).then(function (results) {',
    '      renderEvents((results[0].body && results[0].body.data) || []);',
    '      renderDeliveries((results[1].body && results[1].body.data) || []);',
    '      statusEl.textContent = "updated " + new Date().toLocaleTimeString();',
    '    }).catch(function () { statusEl.textContent = "request failed (check key)"; });',
    '  }',
    '  document.getElementById("save").addEventListener("click", function () {',
    '    localStorage.setItem("signalmesh_key", getKey());',
    '    refresh();',
    '  });',
    '  document.getElementById("refresh").addEventListener("click", refresh);',
    '  document.getElementById("deliveries").addEventListener("click", function (ev) {',
    '    var id = ev.target && ev.target.getAttribute("data-replay");',
    '    if (!id) return;',
    '    api("/v1/deliveries/" + encodeURIComponent(id) + "/replay", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ reason: "dashboard replay" }) })',
    '      .then(refresh).catch(function () {});',
    '  });',
    '  setInterval(refresh, 3000);',
    '  refresh();',
    '})();',
    '</script>',
    '</body>',
    '</html>',
  ].join('\n');
  return html;
}

module.exports = { renderDashboard };
